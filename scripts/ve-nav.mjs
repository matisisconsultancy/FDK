/* ============================================================
   The Velocity Edge · shared menu for note pages and the archive

   One source for the menu markup:
     · scripts/publish-note.mjs puts it on every new note;
     · `node scripts/ve-nav.mjs` refreshes it on every existing
       page (notes from posts.js + /intelligence-library/), so a
       menu change is one edit here plus one run.

   Style: /ve-nav.css · behaviour: /ve-nav.js
   The menu on /velocityedge/ itself is part of that page.
   ============================================================ */
